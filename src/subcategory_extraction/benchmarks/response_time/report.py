def read(relative: str) -> dict[str, Any]:
    """Прочитать исходный отчёт без изменения его происхождения."""
    return json.loads((BENCHMARKS / relative).read_text(encoding="utf-8"))


def model_note(name: str) -> str:
    """Отметить происхождение новых весов и известное использование test при разработке."""
    notes = []
    if name.endswith("::yandex-youla-decision1") or name.endswith("::yandex_youla"):
        notes.append("Published provider-trained weights; provider sample is not an independent holdout.")
    if name.startswith("order_format_joint"):
        notes.append("Published joint module; its README reports official-test examples used during development.")
    if name == "morphology_logistic_regression":
        notes.append("Published Avito weights; train/tune exclusions are recorded in the artifact metadata.")
    return " ".join(notes)


def collect() -> list[dict[str, Any]]:
    """Соединить F1 с latency только при совпадении конфигурации и протокола."""
    latency_report = read("response_time/results.json")
    scopes = []
    for scope_id, title, relative, note in SCOPES:
        if scope_id == "private" and not (BENCHMARKS / relative).exists():
            continue
        report = read(relative)
        rows = []
        n = report["protocol"].get("rows", report["protocol"].get("sample_size"))
        for name, result in report["results"].items():
            metadata = result.get("measurement_metadata", {})
            current = scope_id not in {"official", "manual"} or metadata.get("run_id") in CURRENT_RUNS
            latency: dict[str, Any] = result.get("latency", {})
            if scope_id in {"official", "manual"}:
                candidate = latency_report["results"].get(name, {})
                identity = result.get("comparison_configuration_sha256")
                if (current and identity and identity == candidate.get("comparison_configuration_sha256")
                        and candidate.get("measurement_metadata", {}).get("run_id") == metadata.get("run_id")):
                    latency = candidate
            measured = latency.get("response_time", {}) if latency.get("status") in COMPLETE else {}
            success = result.get("status") in COMPLETE
            module = result.get("module", result.get("configuration", {}).get("module", name))
            rows.append({
                "method": name, "module": module, "group": module.split(".")[0], "current": current,
                "n": n, "completed": len([p for p in result.get("predicted", []) if p is not None]),
                "f1": result.get("metrics", {}).get("micro_f1") if success else None,
                "calls": measured.get("calls", 0),
                **{f"{stat}_ms": measured.get(f"{stat}_seconds", 0) * 1000 if measured else None
                   for stat in ("mean", "median", "p95")},
                "status": result.get("status", "unknown"), "error": result.get("error", ""),
                "latency_status": latency.get("status", "unpaired"), "latency_error": latency.get("error", ""),
                "date": metadata.get("date", report.get("date")), "measurement_metadata": metadata,
                "latency_measurement_metadata": latency.get("measurement_metadata", {}),
                "configuration": result.get("configuration", result.get("comparison_configuration", {})),
                "model_provenance": result.get("model_provenance", {}),
                "model_metadata": result.get("model_metadata"),
                "model_note": model_note(name),
                "reuse": result.get("resumed_predictions", result.get("reused_predictions", 0)),
                "without_exact_train_match": result.get("rows_without_exact_train_match"),
                "source_101_subset": result.get("source_101_subset"),
                "common_subset_metrics": report.get("common_completed_subset", {}).get("metrics_by_method", {}).get(name),
                "per_class_metrics": result.get("per_class_metrics"),
                "metrics_102_106": result.get("metrics_102_106"),
                "model_categories": result.get("model_categories"),
                "trained_categories": result.get("trained_categories"),
                "development_metrics": result.get("development_metrics"),
                "confirmation_metrics": result.get("confirmation_metrics"),
                "timing_scope": latency.get("timing_scope", latency.get("scope", {})),
            })
        rows.sort(key=lambda row: (not row["current"], row["f1"] is None, -(row["f1"] or 0), row["method"]))
        for index, row in enumerate(rows, 1):
            row["index"] = index
        scopes.append({"id": scope_id, "title": title, "note": note, "n": n, "rows": rows,
                       "protocol": report["protocol"], "overlap": report.get("overlap"),
                       "common_subset_rows": report.get("common_completed_subset", {}).get("rows"),
                       "private_audit": report.get("private_audit"),
                       "generalization_study": report.get("generalization_study"),
                       "source": relative, "sha256": hashlib.sha256((BENCHMARKS / relative).read_bytes()).hexdigest()})
    return scopes


def graph(scope: dict[str, Any]) -> str:
    """Построить в памяти самостоятельный SVG с осями времени и micro-F1."""
    if scope["id"] == "private":
        return classification_graph(scope)
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10, "svg.fonttype": "none"})
    fig, axis = plt.subplots(figsize=(11.8, 4.7), layout="constrained")
    fig.patch.set_facecolor("#ffffff")
    axis.set_xscale("log")
    axis.set_ylim(0, 1.045)
    axis.set_xlabel("Mean time per ad · milliseconds · logarithmic scale", labelpad=12)
    axis.set_ylabel("Agreement micro-F1" if scope["id"] == "provider" else "Micro-F1", labelpad=10)
    axis.xaxis.set_major_formatter(FuncFormatter(lambda value, _: f"{value:g}"))
    axis.spines[["top", "right"]].set_visible(False)
    axis.grid(alpha=0.16)
    plotted = []
    for row in scope["rows"]:
        if not row["current"] or row["f1"] is None or row["mean_ms"] is None:
            continue
        point = axis.scatter(row["mean_ms"], row["f1"], color=COLORS.get(row["group"], "#666666"),
                             s=54, edgecolor="white", linewidth=0.7, zorder=3)
        point.set_gid(f"point-{scope['id']}-{row['index']}")
        axis.annotate(str(row["index"]), (row["mean_ms"], row["f1"]), xytext=(5, 5 + (row["index"] % 3) * 5),
                      textcoords="offset points", fontsize=8, color="#263348")
        plotted.append(row)
    if plotted:
        axis.set_xlim(min(row["mean_ms"] for row in plotted) / 1.6, max(row["mean_ms"] for row in plotted) * 1.6)
    axis.set_title(f"{scope['title']} · N={scope['n']:,} · {len(plotted)} complete pairs", loc="left", pad=14,
                   fontweight="bold", color="#172b43")
    return inline_svg(fig, scope, plotted)


def classification_graph(scope: dict[str, Any]) -> str:
    """Показать только F1 для private-test, не выдавая cached inference за latency."""
    rows = [row for row in scope["rows"] if row["f1"] is not None]
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10, "svg.fonttype": "none"})
    fig, axis = plt.subplots(figsize=(11.8, max(4.5, len(rows) * 0.36)), layout="constrained")
    bars = axis.barh(range(len(rows)), [row["f1"] for row in rows],
                     color=[COLORS.get(row["group"], "#666666") for row in rows])
    for bar, row in zip(bars, rows, strict=True):
        bar.set_gid(f"point-{scope['id']}-{row['index']}")
        axis.text(row["f1"] + 0.008, bar.get_y() + bar.get_height() / 2, f"{row['f1']:.4f}", va="center", fontsize=9)
    axis.set_yticks(range(len(rows)), [f"{row['index']}. {row['method']}" for row in rows])
    axis.invert_yaxis()
    axis.set_xlim(0, 1.05)
    axis.set_xlabel("Full-set micro-F1 · all categories 101–106")
    axis.set_title(f"Private test · N={scope['n']} · {len(rows)} complete methods", loc="left", fontweight="bold", pad=14)
    axis.spines[["top", "right"]].set_visible(False)
    axis.grid(axis="x", alpha=0.16)
    axis.set_axisbelow(True)
    return inline_svg(fig, scope, rows)


def inline_svg(fig: Any, scope: dict[str, Any], plotted: list[dict[str, Any]]) -> str:
    """Встроить SVG с уникальными id и подписями без внешних ресурсов."""
    buffer = io.StringIO()
    fig.savefig(buffer, format="svg", metadata={"Date": None})
    plt.close(fig)
    svg = ET.fromstring(buffer.getvalue())
    namespace = "{http://www.w3.org/2000/svg}"
    ET.register_namespace("", "http://www.w3.org/2000/svg")
    ET.register_namespace("xlink", "http://www.w3.org/1999/xlink")
    by_id = {node.attrib.get("id"): node for node in svg.iter()}
    for row in plotted:
        node = by_id[f"point-{scope['id']}-{row['index']}"]
        ET.SubElement(node, namespace + "title").text = (
            f"{row['index']}. {row['method']} | F1 {row['f1']:.6f}"
            + (f" | mean {row['mean_ms']:.3f} ms" if row["mean_ms"] is not None else " | latency not measured")
        )
    # SVG разных графиков находятся в одном DOM и не должны делить id/clipPath.
    identities = {node.attrib["id"]: f"{scope['id']}-{node.attrib['id']}"
                  for node in svg.iter() if "id" in node.attrib}
    for node in svg.iter():
        for key, value in list(node.attrib.items()):
            if key == "id":
                node.set(key, identities[value])
            elif value.startswith("#") and value[1:] in identities:
                node.set(key, "#" + identities[value[1:]])
            elif value.startswith("url(#") and value.endswith(")") and value[5:-1] in identities:
                node.set(key, "url(#" + identities[value[5:-1]] + ")")
    svg.set("role", "img")
    svg.set("aria-label", f"{scope['title']}: micro-F1" + (" against mean latency" if scope["id"] != "private" else ""))
    return ET.tostring(svg, encoding="unicode")


def number(value: float | None, precision: int = 3) -> str:
    """Показать отсутствие метрики явно, не заменяя его нулём."""
    return "—" if value is None else f"{value:.{precision}f}"


def section(scope: dict[str, Any], first: bool) -> str:
    """Сформировать единую таблицу scope с сохранёнными версиями и подробностями."""
    body = []
    private = scope["id"] == "private"
    for row in scope["rows"]:
        details = {key: row[key] for key in ("module", "date", "measurement_metadata", "latency_measurement_metadata",
                                           "configuration", "model_provenance", "model_metadata", "model_note", "timing_scope", "reuse",
                                           "without_exact_train_match", "source_101_subset", "common_subset_metrics",
                                           "per_class_metrics", "metrics_102_106", "model_categories", "trained_categories",
                                           "development_metrics", "confirmation_metrics", "error", "latency_error")}
        name = html.escape(row["method"])
        status = "current" if row["current"] else "preserved"
        error = html.escape(row["error"] or row["latency_error"])
        status_text = row["status"] + (" · preserved" if not row["current"] else "")
        notes = html.escape(row["model_note"])
        if private:
            no_train = ((row["without_exact_train_match"] or {}).get("metrics") or {}).get("micro_f1")
            common = (row["common_subset_metrics"] or {}).get("micro_f1")
            timing_cells = f'<td>{number(no_train, 6)}</td><td>{number(common, 6)}</td>'
            if scope["generalization_study"]:
                timing_cells += (f'<td>{number((row["development_metrics"] or {}).get("micro_f1"), 6)}</td>'
                                 f'<td>{number((row["confirmation_metrics"] or {}).get("micro_f1"), 6)}</td>')
        else:
            timing_cells = (f'<td>{number(row["mean_ms"])}</td><td>{number(row["median_ms"])}</td>'
                            f'<td>{number(row["p95_ms"])}</td><td>{row["calls"]}</td>')
        body.append(
            f'<tr data-kind="{status}" data-method="{name.lower()}"><td>{row["index"]}</td>'
            f'<td><details><summary>{name}</summary><p>{notes}</p><pre>{html.escape(json.dumps(details, ensure_ascii=False, indent=2))}</pre></details></td>'
            f'<td>{row["completed"]}/{row["n"]}</td><td>{number(row["f1"], 6)}</td>'
            f'{timing_cells}<td title="{error}">{html.escape(status_text)}'
            f'{"<br><small>" + error[:180] + "</small>" if error else ""}</td><td>{html.escape(row["date"] or "unknown")}</td></tr>'
        )
    protocol = json.dumps({"protocol": scope["protocol"], "overlap": scope["overlap"], "source": scope["source"],
                           "source_sha256": scope["sha256"], "private_audit": scope["private_audit"]}, ensure_ascii=False, indent=2)
    explanation = (f'All six labels; full-set failures receive no F1. No-train N=222; common completed subset N={scope["common_subset_rows"]}. '
                   'Click a method for per-class scores and provenance. Latency was not measured.' if private else
                   'Point numbers identify table rows. Hover a point for its method. Only complete, matching F1 / latency pairs are plotted. '
                   'Click a method to inspect provenance.')
    metric_headers = ('<th>No-train F1</th><th>Common-subset F1</th>' if private else
                      '<th>Mean ms</th><th>Median ms</th><th>p95 ms</th><th>Time N</th>')
    study_note = ""
    if private and scope["generalization_study"]:
        metric_headers += '<th>Development F1</th><th>Confirmation F1</th>'
        study = scope["generalization_study"]
        interval = study["confirmation_group_bootstrap_95_interval"]
        study_note = (f'<p class="notice"><b>Frozen generalization study:</b> {study["development_rows"]} development / '
                      f'{study["confirmation_rows"]} grouped confirmation ads. Winner selected before confirmation; '
                      'thresholds fitted only on 96 manual-train groups and checked on 48 separate control groups. '
                      f'Confirmation group-bootstrap 95% interval: {interval[0]:.3f}–{interval[1]:.3f}. '
                      'The small confirmation set is not a pristine external test: baseline full-set aggregates were already known. '
                      'No ad-specific IDs, text hashes or answer lookups are used by the model. '
                      'The new arbiter slightly regresses on the official/manual tests; defaults are unchanged.</p>')
    return (
        f'<section id="{scope["id"]}" class="scope" {"" if first else "hidden"}>'
        f'<h2>{scope["title"]}</h2><p class="notice">{html.escape(scope["note"])}</p>{study_note}'
        f'<div class="chart">{graph(scope)}</div><p class="muted">{explanation}</p>'
        '<div class="table-scroll"><table><thead><tr>'
        f'<th>#</th><th>Method / configuration</th><th>F1 rows</th><th>Micro-F1</th>{metric_headers}<th>Status</th><th>Measured at</th>'
        f'</tr></thead><tbody>{"".join(body)}</tbody></table></div>'
        f'<details class="protocol"><summary>Dataset protocol, overlap and source hash</summary><pre>{html.escape(protocol)}</pre></details></section>'
    )


def study_summary(scopes: list[dict[str, Any]]) -> str:
    """Показать итог подтверждённого улучшения сразу при открытии отчёта."""
    private = next((scope for scope in scopes if scope["id"] == "private"), None)
    if not private or not private.get("generalization_study"):
        return ""
    study = private["generalization_study"]
    key = study["selected_module"].rsplit(".", 1)[-1]
    winner = next(row for row in private["rows"] if row["method"] == key)
    baseline = next(row for row in private["rows"] if row["method"] == "jev_calibrated")
    no_train = winner["without_exact_train_match"]
    interval = study["confirmation_group_bootstrap_95_interval"]
    timing = study["timing"][key]
    official = study["regressions"]["official"][key]["micro_f1"]
    manual = study["regressions"]["manual"][key]["micro_f1"]
    cards = (
        ("Full private set", f"{winner['f1']:.4f}", f"micro-F1 · {private['n']} ads · all six categories"),
        ("Reserved confirmation", f"{winner['confirmation_metrics']['micro_f1']:.4f}",
         f"micro-F1 · {study['confirmation_rows']} grouped ads"),
        ("No exact training matches", f"{no_train['metrics']['micro_f1']:.4f}", f"micro-F1 · {no_train['rows']} ads"),
        ("Improvement over calibrated Jev", f"+{100 * (winner['f1'] - baseline['f1']):.2f} pp",
         f"{baseline['f1']:.4f} → {winner['f1']:.4f} on the same private set"),
    )
    metrics = "".join(f'<div class="result-card"><span>{html.escape(label)}</span><strong>{value}</strong>'
                      f'<small>{html.escape(note)}</small></div>' for label, value, note in cards)
    return (
        '<aside class="result-summary" aria-label="Confirmed semantic classifier results">'
        '<div class="eyebrow">Confirmed private-set improvement</div>'
        f'<h2><code>{html.escape(study["selected_module"])}</code></h2>'
        f'<div class="result-grid">{metrics}</div>'
        f'<p>The winner was frozen after {study["development_rows"]} development ads, before confirmation. '
        'Threshold selection used training data only; the model has no ad-specific answer lookups. '
        f'The {study["confirmation_rows"]}-ad confirmation remains small: its 95% group-bootstrap interval is '
        f'{interval[0]:.3f}–{interval[1]:.3f}. Baseline full-set aggregates were already known.</p>'
        f'<p class="muted">Trade-offs: {timing["mean_seconds"]:.2f} s/ad mean on {timing["calls"]} uncached public validation inputs; '
        f'official/manual-test F1 {official:.4f}/{manual:.4f}, slightly below calibrated Jev. '
        'The default configuration is unchanged.</p>'
        '<button id="open-private" type="button">View private chart and full comparison</button></aside>'
    )


