def search_text(text: str) -> str:
    """Для поиска сопоставить похожие латинские буквы в смешанных русских словах."""
    return re.sub(
        r"\w+", lambda m: m.group().translate(CONFUSABLES)
        if re.search("[а-яА-ЯёЁ]", m.group()) else m.group(), text,
    )


def load_train_audit() -> tuple[dict, dict]:
    """Проверить train и пересчитать близкие пары без использования test."""
    previous = json.loads(AUDIT.read_text(encoding="utf-8"))
    fingerprint = hashlib.sha256(TRAIN.read_bytes()).hexdigest()
    if fingerprint != previous["sha256"][TRAIN.name]:
        raise ValueError("Train изменился после исходного аудита")
    raw = [json.loads(line) for line in TRAIN.read_text(encoding="utf-8").splitlines()]
    records = [row for row in previous["records"] if row["split"] == "train"]
    if len(raw) != len(records):
        raise ValueError("Число строк кэша не совпадает с train")
    for index, (source, row) in enumerate(zip(raw, records, strict=True), 1):
        if (row["row"] != index or source["description"] != row["description"]
                or source["item_id"] != row["item_id"] or source["title"] != row["title"]
                or sorted(e["mcId"] for e in source["found_microcategories"]) != row["labels"]):
            raise ValueError(f"Несогласованная строка train: {index}")
    groups = duplicate_groups(records, "normalized")
    audit = {
        "records": records,
        "sha256": {TRAIN.name: fingerprint},
        "train": previous["train"],
        "normalized_groups": groups,
        "normalized": describe_groups(records, groups),
        "candidates": semantic_candidates(records),
        "near_duplicates": near_duplicates(records, groups),
    }
    sources = {("train", index): row for index, row in enumerate(raw, 1)}
    return audit, sources


def missing_groups(audit: dict) -> list[tuple[str, dict[int, dict], list[int]]]:
    """Сгруппировать все пропуски лексических сигналов по точному description."""
    flags: dict[str, dict[int, dict]] = defaultdict(dict)
    copies = defaultdict(list)
    for index, row in enumerate(audit["records"]):
        copies[row["description"]].append(index)
    for candidate in audit["candidates"]["missing_signal"]:
        text = audit["records"][candidate["index"]]["description"]
        flags[text].setdefault(candidate["category"], candidate)
    return [(text, items, copies[text]) for text, items in flags.items()]


def plaster_groups(audit: dict) -> list[list[int]]:
    """Найти метку 102 без штукатурки или выравнивания как кандидата на проверку."""
    found = defaultdict(list)
    for index, row in enumerate(audit["records"]):
        if 102 in row["labels"] and not re.search(
            r"штукатур|выравн", search_text(row["description"]), re.I,
        ):
            found[row["description"]].append(index)
    return list(found.values())


