def candidate_sections(report: Report, missing: list, plaster: list[list[int]]) -> None:
    """Показать все отобранные train-группы с доказательствами и полными строками."""
    report.add('<a id="train-candidates"></a>', "## 5. Полный каталог train-кандидатов по правилам", "",
               "### 5.1. Сигнал услуги есть, метки нет", "",
               "**Статус всех M-групп:** автоматический кандидат. Ниже не назначается "
               "исправленный эталон. Совпадение может быть отрицанием, поисковым "
               "словом, описанием материалов, чужих услуг или объявлением заказчика. "
               "Ручные вердикты есть только у перечисленных в разделе 4 случаев.", "")
    for number, (text, flags, copies) in enumerate(missing, 1):
        report.add(f"#### M{number:03d}. Train {report.rows[copies[0]]['row']}: "
                   f"нет меток {', '.join(map(str, sorted(flags)))}", "",
                   f"**Размер группы:** {len(copies)} точных копий.", "",
                   "**Сравниваем:** фактический набор источника и категории, "
                   "на которые указывает лексический сигнал. Это не готовое предсказание.", "")
        report.matrix(copies)
        for cid, flag in sorted(flags.items()):
            report.add(f"**Сигнал {cid}; метка отсутствует:**", "",
                       *(fenced(evidence) + "\n" for evidence in flag["evidence"]), "")
        report.add("<details>", "<summary>Полный общий description группы</summary>", "",
                   fenced(text), "", "</details>", "")
    report.add("### 5.2. Метка 102 без упоминания штукатурки или выравнивания", "",
               "**Статус всех G-групп:** автоматический кандидат, не доказанная лишняя "
               "метка. В поисковой копии текста сопоставлены похожие латинские "
               "буквы только в словах, содержащих кириллицу. Исходники не меняются.", "",
               "**Точное условие:** есть метка 102, но после такого сопоставления "
               "нет основ `штукатур` и `выравн`. Опечатки, синонимы и неявные "
               "контексты могут давать ложные срабатывания.", "")
    for number, group in enumerate(plaster, 1):
        report.add(f"#### G{number:03d}. Train {report.rows[group[0]]['row']}: "
                   "102 без определяющих основ", "")
        report.matrix(group)
        report.add("<details>", "<summary>Полный общий description группы</summary>", "",
                   fenced(report.rows[group[0]]["description"]), "", "</details>", "")


