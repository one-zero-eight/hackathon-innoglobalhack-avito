    def near_pairs(self, split: str | None = None) -> None:
        """Показать все автоматически найденные близкие пары с разными метками."""
        pairs = [
            p for p in self.audit["near_duplicates"]["pairs"]
            if p["different_labels"] and (
                split is None or all(self.rows[p[key]]["split"] == split for key in ("left", "right"))
            )
        ]
        self.add('<a id="near-pairs"></a>', "## 7. Все близкие пары с разными метками: кандидаты", "",
                 f"Всего {len(pairs)} пар. **Это не {len(pairs)} ошибок.** "
                 "Шаблонное сходство может быть высоким, а список предлагаемых работ — "
                 "обоснованно различным. Отдельный смысловой вердикт каждой паре не назначен.", "",
                 "**Метод:** " + self.audit["near_duplicates"]["method"] + ".", "",
                 "Для каждой пары сохранены полные исходные строки, фактические наборы "
                 "и построчный diff. Показаны представители нормализованных групп, "
                 "а не все комбинации их дубликатов.", "")
        for number, pair in enumerate(pairs, 1):
            left, right = pair["left"], pair["right"]
            a, b = self.rows[left], self.rows[right]
            self.add(f"### N{number:03d}. {a['split']}:{a['row']} ↔ "
                     f"{b['split']}:{b['row']} · cosine {pair['cosine']:.6f}", "",
                     "**Статус:** автоматический кандидат, не подтверждённая ошибка.", "")
            self.matrix([left, right])
            self.add("**Заголовки:**", "", fenced(a["title"]), "", fenced(b["title"]), "")
            self.diff(left, right)

