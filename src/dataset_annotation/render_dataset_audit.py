def fenced(text: str, language: str = "text") -> str:
    """Безопасно поместить исходный текст в блок без изменения содержимого."""
    size = max([3, *(len(m.group()) + 1 for m in re.finditer(r"`+", text))])
    fence = "`" * size
    return f"{fence}{language}\n{text}\n{fence}"


def labels(values: list[int] | set[int]) -> str:
    """Показать набор ID в стабильном порядке."""
    return "`" + json.dumps(sorted(values)) + "`"


def load_sources(audit: dict) -> dict[tuple[str, int], dict]:
    """Прочитать именно исходные поля и проверить соответствие аудиту."""
    sources = {}
    for name, expected in audit["sha256"].items():
        if hashlib.sha256((DATA / name).read_bytes()).hexdigest() != expected:
            raise ValueError(f"Исходник изменился после аудита: {name}")
    train = [json.loads(line) for line in
             (DATA / "public-train-annotated.jsonl").read_text().splitlines()]
    test = pq.read_table(DATA / "public-test-dataset.parquet").to_pylist()
    for split, part in (("train", train), ("test", test)):
        for number, raw in enumerate(part, 1):
            sources[split, number] = raw
    reverse = {name: cid for cid, name in MICROCATEGORIES.items()}
    for row in audit["records"]:
        raw = sources[row["split"], row["row"]]
        actual = (
            [entry["mcId"] for entry in raw["found_microcategories"]]
            if row["split"] == "train" else [reverse[name] for name in raw["categories"]]
        )
        if (raw["description"] != row["description"] or raw["title"] != row["title"]
                or sorted(actual) != row["labels"]):
            raise ValueError("Кэш аудита не соответствует исходной записи")
    return sources


class Report:
    """Собирать сравнения и каталог полных строк без их многократного копирования."""

    def __init__(self, audit: dict, sources: dict[tuple[str, int], dict]) -> None:
        self.audit = audit
        self.sources = sources
        self.rows = audit["records"]
        self.lines: list[str] = []
        self.selected: set[int] = set()

    def add(self, *lines: str) -> None:
        """Добавить Markdown-блоки."""
        self.lines.extend(lines)

    def ref(self, index: int) -> str:
        """Зарегистрировать полную запись и вернуть ссылку на неё."""
        self.selected.add(index)
        row = self.rows[index]
        return f"[{row['split']}:{row['row']}](#record-{row['split']}-{row['row']})"

    def find(self, split: str, number: int) -> int:
        """Найти индекс по исходному номеру строки."""
        return next(i for i, r in enumerate(self.rows)
                    if r["split"] == split and r["row"] == number)

    def matrix(self, indices: list[int]) -> None:
        """Показать фактические метки и разницу относительно первой записи."""
        base = set(self.rows[indices[0]]["labels"])
        self.add(
            "| Полная запись | item_id | Фактические ID | + к первой строке | − из первой строки |",
            "| --- | --- | --- | --- | --- |",
        )
        for index in indices:
            row = self.rows[index]
            actual = set(row["labels"])
            self.add(f"| {self.ref(index)} | {row.get('item_id', 'нет в источнике')} | "
                     f"{labels(actual)} | {labels(actual - base)} | {labels(base - actual)} |")
        self.add("", "Первая строка — **база сравнения, не эталон**.", "")

    def description(self, index: int) -> None:
        """Показать полное описание, не интерпретируя его Markdown-разметку."""
        self.add("**Полный description:**", "", fenced(self.rows[index]["description"]), "")

    def diff(self, left: int, right: int) -> None:
        """Показать точное построчное изменение описаний пары."""
        a, b = self.rows[left], self.rows[right]
        delta = "\n".join(difflib.unified_diff(
            a["description"].splitlines(), b["description"].splitlines(),
            fromfile=f"{a['split']}:{a['row']}", tofile=f"{b['split']}:{b['row']}", n=2,
        ))
        self.add(f"**description:** {'дословно одинаковый' if not delta else 'различается'}.", "")
        if delta:
            self.add("<details>", "<summary>Построчное сравнение description</summary>", "",
                     fenced(delta, "diff"), "", "</details>", "")

    def exact_conflicts(self) -> None:
        """Разобрать все конфликтные группы точных описаний внутри test."""
        self.add('<a id="test-conflicts"></a>', "## 3. Все 13 конфликтных групп test", "",
                 "В каждой группе title и description дословно одинаковы. "
                 "Исходный mcId в parquet отсутствует. Наборы ниже — метки источника; "
                 "моя интерпретация не подменяет официальный эталон.", "")
        groups = self.audit["test"]["exact_duplicates"]["conflicting_groups"]
        for number, local in enumerate(groups, 1):
            indices = [self.find("test", i + 1) for i in local]
            first = self.rows[indices[0]]["row"]
            counts = Counter(tuple(self.rows[i]["labels"]) for i in indices)
            self.add(f"### T{number:02d}. Test {', '.join(str(i + 1) for i in local)}", "",
                     "**Статус:** подтверждённое различие меток одинакового текста.", "",
                     f"**Заголовок:** {self.rows[indices[0]]['title']}", "",
                     "**Меняется:** поле `categories`. **Не меняются:** `title`, `description`.", "",
                     "**Частоты вариантов:** " + "; ".join(
                         f"{labels(set(key))} — {count} строк" for key, count in counts.items()
                     ) + ".", "")
            self.matrix(indices)
            self.add("**Смысловой разбор:** " + TEST_REVIEW[first], "",
                     "**Рекомендация:** согласовать один набор при одинаковом исходном mcId; "
                     "не выбирать автоматически большинство как истинную разметку.", "")
            self.description(indices[0])

    def semantic(self, cases: list | None = None) -> None:
        """Показать смысловые случаи и все их точные копии."""
        self.add('<a id="semantic"></a>', "## 4. Смысловые случаи train", "",
                 "Полные исходные строки всех точных копий включены в каталог. "
                 "Предлагаемые наборы — интерпретация справочника для исходной 101, "
                 "а не автоматически внесённые исправления.", "")
        selected_cases = SEMANTIC_CASES if cases is None else cases
        for number, (row_number, proposed, title, confidence, reason) in enumerate(selected_cases, 1):
            index = self.find("train", row_number)
            row = self.rows[index]
            copies = [i for i, r in enumerate(self.rows)
                      if r["split"] == "train" and r["description"] == row["description"]]
            self.add(f"### S{number:02d}. {title}", "",
                     f"**Уверенность:** {confidence}.", "",
                     f"**Основная запись:** {self.ref(index)}; item_id `{row['item_id']}`.", "",
                     "| Сравнение | Набор |", "| --- | --- |",
                     f"| Разметка источника | {labels(row['labels'])} |",
                     f"| Предлагаемая интерпретация | "
                     f"{labels(proposed) if proposed is not None else 'Не фиксируется до согласования правила'} |",
                     "", "**Основание:** " + reason, "",
                     f"**Масштаб:** {len(copies)} дословных копий в train. "
                     "Это число записей, а не независимых подтверждений ошибки.", "")
            self.description(index)
            self.add("<details>", "<summary>Все исходные строки этой группы</summary>", "")
            self.matrix(copies)
            self.add("</details>", "")

    def cross_split(self) -> None:
        """Показать все пересечения частей, включая различия нормализации."""
        self.add('<a id="overlap"></a>', "## 5. Все пересечения train/test после нормализации", "",
                 "Всего 13 групп и 24 строки test. Это риск утечки при оценке, "
                 "не обязательно ошибка каждой метки. Каждая запись приведена полностью.", "")
        for number, group in enumerate(self.audit["normalized"]["cross_split_groups"], 1):
            first = group[0]
            exact = len({self.rows[i]["description"] for i in group}) == 1
            self.add(f"### X{number:02d}. {'Дословное' if exact else 'Нормализованное'} совпадение", "",
                     f"**Статус:** подтверждённое пересечение частей; "
                     f"различных наборов меток: {len({tuple(self.rows[i]['labels']) for i in group})}.", "")
            self.matrix(group)
            self.description(first)
            variants = {}
            for index in group:
                variants.setdefault(self.rows[index]["description"], index)
            for index in list(variants.values())[1:]:
                self.diff(first, index)
            self.add("**Рекомендация:** учитывать группу как один связанный источник "
                     "при разбиении и отдельно раскрывать пересечение в результатах оценки.", "")

